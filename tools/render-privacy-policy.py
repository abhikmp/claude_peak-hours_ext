"""Render the maintained Markdown policy as a standalone GitHub Pages document."""
import argparse
import html
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/release/privacy-policy.md'
OUTPUT = ROOT / 'docs/privacy-policy.html'


def render():
    blocks = []
    for paragraph in SOURCE.read_text(encoding='utf-8').strip().split('\n\n'):
        line = paragraph.strip()
        heading = re.fullmatch(r'(#{1,6}) (.+)', line)
        if heading:
            level = len(heading[1])
            blocks.append(f'<h{level}>{html.escape(heading[2])}</h{level}>')
        else:
            value = html.escape(line).replace('\n', ' ')
            value = re.sub(r'\[([^\]]+)\]\((https://[^)]+)\)',
                           r'<a href="\2">\1</a>', value)
            blocks.append('<p>' + value + '</p>')
    return '''<!doctype html>
<!-- Generated by python tools/render-privacy-policy.py from docs/release/privacy-policy.md. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>ClaudeBuddy Privacy Policy</title><style>body{font-family:system-ui,sans-serif;line-height:1.65;max-width:48rem;margin:3rem auto;padding:0 1.25rem;color:#202124;background:#fff}h1,h2{line-height:1.25}a{color:#1558a6}h2{margin-top:2rem}</style></head><body><main>''' + '\n'.join(blocks) + '''</main></body></html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the HTML needs regeneration')
    args = parser.parse_args()
    expected = render().encode('utf-8')
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != expected:
            raise SystemExit('Policy HTML is stale; run python tools/render-privacy-policy.py')
        print('Policy HTML matches its Markdown source.')
    else:
        OUTPUT.write_bytes(expected)
        print('Rendered docs/privacy-policy.html')


if __name__ == '__main__':
    main()
